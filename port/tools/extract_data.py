#!/usr/bin/env python3
"""Extract the data blocks the port needs (graphics, tables, screen texts)
from the original PRG into port/src/gamedata.c. At start-up the port copies
each block to its original address in its emulated VC20 memory.

Usage: extract_data.py original/LUFTKAMPF.prg > port/src/gamedata.c
"""
import sys

prg = open(sys.argv[1], "rb").read()
mem = prg[2:]          # runs from $0401 (see src/luftkampf.cfg)
BASE = 0x0401

# (start address, length, comment) -- names as in src/labels.txt
REGIONS = [
    (0x0497, 0x39,  "expl_volume: explosion volume envelope"),
    (0x05F5, 0x1A,  "txt_game_over / title text"),
    (0x0652, 0x20,  "gfx_player: player plane, 4 directions x 8 bytes"),
    (0x0684, 0x18,  "txt_attention: 'ACHTUNG ! PILOT'"),
    (0x07E5, 0x3E,  "txt_scores"),
    (0x0CAC, 0x4E,  "txt_menu: 'ANZAHL PILOTEN'"),
    (0x12F2, 0x20,  "gfx_shot: shot, 4 directions x 8 bytes"),
    (0x1595, 0x0B,  "txt_blank"),
    (0x1A00, 0x200, "gfx_planes: enemy plane characters $40-$7F"),
    (0x1C00, 0x200, "initial content of characters $80-$BF"),
]

print("/* Generated by port/tools/extract_data.py from original/LUFTKAMPF.prg.")
print(" * Graphics, tables and texts of the original game (c) Commodore 1982. */")
print('#include "gamedata.h"\n')
names = []
for addr, n, comment in REGIONS:
    data = mem[addr - BASE: addr - BASE + n]
    name = f"blk_{addr:04x}"
    names.append((name, addr, n))
    print(f"/* ${addr:04X}: {comment} */")
    print(f"static const unsigned char {name}[{n}] = {{")
    for i in range(0, n, 16):
        print("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    print("};\n")
print("const struct data_block game_data[] = {")
for name, addr, n in names:
    print(f"    {{0x{addr:04X}, {n}, {name}}},")
print("    {0, 0, 0}")
print("};")
